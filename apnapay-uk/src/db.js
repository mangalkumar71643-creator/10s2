// Every query inside db.tx() automatically uses the transaction's connection.
const txStore = new AsyncLocalStorage();
let driver = null; // { query(sql, params) -> rows, transaction(fn), close() }
let readyPromise = null;
let lastOpts = null;
let failed = false;

// We write "?" placeholders; Postgres wants $1, $2 ...
function toPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

async function makePg(url) {
  const pg = require('pg');
  pg.types.setTypeParser(20, Number); // bigint (timestamps, paise) -> JS number
  pg.types.setTypeParser(1700, Number); // numeric (SUM results)
  const local = /@(localhost|127\.0\.0\.1)[:/]/.test(url);
  const pool = new pg.Pool({
    connectionString: url,
    max: Number(process.env.DB_POOL_MAX || 5),
    ssl: local ? false : { rejectUnauthorized: false },
    idleTimeoutMillis: 10000,
  });
  return {
    query: async (sql, params) => (await pool.query(toPg(sql), params)).rows,
    transaction: async (fn) => {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        // One writer at a time for orders/matching, so unique amounts can never clash.
        await client.query('SELECT pg_advisory_xact_lock(7741)');
        const result = await fn({ query: async (sql, params) => (await client.query(toPg(sql), params)).rows });
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function makePglite(dataDir) {
  const { PGlite } = require('@electric-sql/pglite');
  if (dataDir) fs.mkdirSync(dataDir, { recursive: true });
  const lite = await PGlite.create(dataDir || undefined, { parsers: { 20: Number, 1700: Number } });
  return {
    query: async (sql, params) => (await lite.query(toPg(sql), params)).rows,
    transaction: (fn) => lite.transaction((tx) => fn({ query: async (sql, params) => (await tx.query(toPg(sql), params)).rows })),
    close: () => lite.close(),
  };
}

/**
 * @param {{ url?: string, dataDir?: string|null }} opts  url = Postgres URL; dataDir null = in memory
 */
function init({ url, dataDir } = {}) {
  lastOpts = { url, dataDir };
  failed = false;
  readyPromise = (async () => {
    if (driver) await driver.close().catch(() => {});
    driver = url ? await makePg(url) : await makePglite(dataDir);
    await exec(SCHEMA);
  })();
  readyPromise.catch(() => {
    failed = true;
  });
  return readyPromise;
}

function ready() {
  if (!readyPromise) return Promise.reject(new Error('Database not initialised'));
  if (failed) return init(lastOpts); // e.g. Neon was waking up: try again on the next request
  return readyPromise;
}

async function exec(sql) {
  // Run statements one by one (works for both drivers).
  for (const stmt of sql.split(/;\s*\n/).map((s) => s.replace(/--.*$/gm, '').trim()).filter(Boolean)) {
    await driver.query(stmt, []);
  }
}

async function query(sql, params = []) {
  await ready();
  const tx = txStore.getStore();
  return tx ? tx.query(sql, params) : driver.query(sql, params);
}

const all = (sql, ...params) => query(sql, params);
const get = async (sql, ...params) => (await query(sql, params))[0];
// For INSERTs add "RETURNING id" and read .rows[0].id
const run = async (sql, ...params) => ({ rows: await query(sql, params) });

async function tx(fn) {
  await ready();
  if (txStore.getStore()) return fn(); // already inside a transaction
  const hooks = [];
  const result = await driver.transaction((client) => txStore.run({ query: client.query, hooks }, fn));
  const { background } = require('./background');
  for (const hook of hooks) background(hook);
  return result;
}

// Run fn once the current transaction has committed (or right away when not in one).
function afterCommit(fn) {
  const t = txStore.getStore();
  if (t) t.hooks.push(fn);
  else require('./background').background(fn);
}

// Run fn outside any surrounding transaction (for work that continues after it commits).
function detached(fn) {
  return txStore.exit(fn);
}

const DEFAULT_SETTINGS = {
  business_name: 'Demo Store UK',
  order_expiry_minutes: '30',
  // Smallest order (£) a customer can be asked to pay.
  min_order_amount: '1',
  late_match_hours: '24',
  // 1 = a payment without our reference is still accepted when exactly one open order has that amount.
  accept_amount_only: '1',
  telegram_bot_token: '',
  telegram_chat_id: '',
  support_email: '',
  demo_shop_site_id: '',
};

async function getSettings() {
  const out = { ...DEFAULT_SETTINGS };
  for (const row of await all('SELECT key, value FROM settings')) out[row.key] = row.value;
  return out;
}

function setSetting(key, value) {
  return run(
    'INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value',
    key,
    String(value),
  );
}

function logActivity(level, message) {
  return run('INSERT INTO activity (level, message, created_at) VALUES (?, ?, ?)', level, message, Date.now());
}

module.exports = { init, ready, get, all, run, tx, detached, afterCommit, getSettings, setSetting, logActivity, DEFAULT_SETTINGS };
